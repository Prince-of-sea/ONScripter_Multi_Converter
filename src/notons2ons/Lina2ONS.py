def read_kbp(path):
    with open(path, "rb") as f:
        b = f.read()
    if b[:4] != b"KBP1":
        raise ValueError("not KBP1: " + path)
    w, h, hdr = struct.unpack_from("<3I", b, 8)
    px = b[hdr:hdr + w * h * 4]
    if len(px) != w * h * 4:
        raise ValueError("truncated: " + path)
    return w, h, px


def bgra_to_rgba(px):
    out = bytearray(px)
    out[0::4] = px[2::4]
    out[2::4] = px[0::4]
    alpha = px[3::4]
    if max(alpha, default=0) <= 63:
        # the game stores a 6-bit alpha (0-63)
        out[3::4] = bytes((a * 255 + 31) // 63 for a in alpha)
    return bytes(out)


def write_png(path, w, h, rgba):
    raw = bytearray()
    stride = w * 4
    for y in range(h):
        raw.append(0)
        raw += rgba[y * stride:(y + 1) * stride]

    def chunk(tag, data):
        c = struct.pack(">I", len(data)) + tag + data
        return c + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)

    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0)))
        f.write(chunk(b"IDAT", zlib.compress(bytes(raw), 6)))
        f.write(chunk(b"IEND", b""))


def convert_kbp(src, dst):
    w, h, px = read_kbp(src)
    write_png(dst, w, h, bgra_to_rgba(px))
    return w, h


Ins = namedtuple("Ins", "off kind a b c")


OPS = {
    0x180: '*', 0x181: '/', 0x182: '%', 0x183: '+', 0x184: '-', 0x185: '&', 0x186: '|',
    0x187: '^', 0x188: '<<', 0x189: '>>', 0x18a: '>', 0x18b: '>=', 0x18c: '<', 0x18d: '<=',
    0x18e: '&&', 0x18f: '||', 0x190: '=', 0x191: '==', 0x192: '!=',
}


class Script:
    def __init__(self, data):
        if data[:4] != b"SVS1":
            raise ValueError("not SVS1")
        self.b = data
        self.code_mid, self.pool, self.total = struct.unpack_from("<3I", data, 4)
        self.hdr = struct.unpack_from("<I", data, 0x14)[0]
        self.labels = list(struct.unpack_from("<1024I", data, 0x20))

    def string(self, rel):
        s = self.pool + rel
        return self.b[s:self.b.find(b"\0", s)].decode("cp932", "replace")

    def u16(self, o):
        return struct.unpack_from("<H", self.b, o)[0]

    def u32(self, o):
        return struct.unpack_from("<I", self.b, o)[0]

    def expr(self, o):
        """Parse the expression at o (a 0x200/0x201 word). Returns ((kind, items), next_offset)."""
        kind = self.u16(o)
        o += 2
        items = []
        while True:
            t = self.u16(o)
            if t == 0x19f:
                return (kind, items), o + 2
            if t in (0x101, 0x108) or (t == 0x102 and kind == 0x201):
                sub, o = self.expr(o + 2)
                items.append(('vi', t, sub))
            elif t in (0x10b, 0x10e) and kind == 0x200:
                imm = self.u32(o + 2)
                sub, o = self.expr(o + 6)
                items.append(('vk', t, imm, sub))
            elif t == 0x10c and kind == 0x200:
                raise ValueError("inline call at 0x%x" % o)
            elif t in OPS:
                items.append(('op', t))
                o += 2
            elif t == 0x200:
                sub, o = self.expr(o)
                items.append(('sub', sub))
            else:
                items.append(('t', t, self.u32(o + 2)))
                o += 6

    def disasm(self, start=None, end=None):
        o = self.hdr if start is None else start
        end = self.pool if end is None else end
        out = []
        while o < end:
            w = self.u16(o)
            if w in (0x200, 0x201):
                e, n = self.expr(o)
                out.append(Ins(o, 'expr', e, None, None))
                o = n
            elif w == 0x314:
                out.append(Ins(o, 'push', None, None, None))
                o += 2
            elif 0x1000 <= w <= 0x17ff:
                out.append(Ins(o, 'cmd', w & 0x7ff, None, None))
                o += 2
            elif w in (0x300, 0x301, 0x302):
                out.append(Ins(o, {0x300: 'jmp', 0x301: 'jf', 0x302: 'jt'}[w], self.u32(o + 2), None, None))
                o += 6
            elif w == 0x303:
                out.append(Ins(o, 'case', self.u32(o + 2), self.u32(o + 6), None))
                o += 10
            elif w in (0x305, 0x310):
                out.append(Ins(o, 'jmpl' if w == 0x305 else 'calll', self.u16(o + 2), None, None))
                o += 4
            elif w in (0x311, 0x317):
                out.append(Ins(o, 'ret', w, self.u16(o + 2), None))
                o += 4
            elif w in (0x312, 0x31a):
                out.append(Ins(o, 'frame', self.u16(o + 2), self.u32(o + 4), None))
                o += 8
            elif w in (0x318, 0x319):
                out.append(Ins(o, 'frame', self.u16(o + 2), None, None))
                o += 4
            else:
                raise ValueError("unknown word 0x%x at 0x%x" % (w, o))
        return out


class Unsupported(Exception):
    pass


def sgn(v):
    return v - (1 << 32) if v >= 0x80000000 else v


def parse_expr(sc, e):
    """RPN expression -> tree.

    ('c', int) ('s', str) ('v', token, address) ('vi', token, index) ('vk', token, base, index)
    ('bin', op, l, r) ('asg', lhs, rhs)
    """
    kind, items = e
    st = []
    for it in items:
        k = it[0]
        if k == 't':
            t, v = it[1], it[2]
            if t == 0x100:
                st.append(('c', sgn(v)))
            elif t == 0x105 and kind == 0x201:
                st.append(('s', sc.string(v)))
            else:
                st.append(('v', t, sgn(v)))
        elif k == 'vi':
            st.append(('vi', it[1], parse_expr(sc, it[2])))
        elif k == 'vk':
            st.append(('vk', it[1], it[2], parse_expr(sc, it[3])))
        elif k == 'sub':
            st.append(parse_expr(sc, it[1]))
        else:
            op = OPS[it[1]]
            r = st.pop()
            l = st.pop()
            st.append(('asg', l, r) if op == '=' else ('bin', op, l, r))
    return st[-1] if st else ('c', 0)


CONST_OPS = {
    '+': lambda a, b: a + b, '-': lambda a, b: a - b, '*': lambda a, b: a * b,
    '/': lambda a, b: int(a / b) if b else 0, '%': lambda a, b: a % b if b else 0,
    '&': lambda a, b: a & b, '|': lambda a, b: a | b, '^': lambda a, b: a ^ b,
    '<<': lambda a, b: a << b, '>>': lambda a, b: a >> b,
    '==': lambda a, b: int(a == b), '!=': lambda a, b: int(a != b), '<': lambda a, b: int(a < b),
    '>': lambda a, b: int(a > b), '<=': lambda a, b: int(a <= b), '>=': lambda a, b: int(a >= b),
    '&&': lambda a, b: int(bool(a) and bool(b)), '||': lambda a, b: int(bool(a) or bool(b)),
}


def fold(ast, consts):
    k = ast[0]
    if k == 'v':
        key = (ast[1], ast[2])
        return ('c', consts[key]) if key in consts else ast
    if k == 'vi':
        idx = fold(ast[2], consts)
        if idx[0] == 'c' and (ast[1], idx[1]) in consts:
            return ('c', consts[(ast[1], idx[1])])
        return ('vi', ast[1], idx)
    if k == 'vk':
        return ('vk', ast[1], ast[2], fold(ast[3], consts))
    if k == 'bin':
        l, r = fold(ast[2], consts), fold(ast[3], consts)
        if l[0] == 'c' and r[0] == 'c' and ast[1] in CONST_OPS:
            return ('c', CONST_OPS[ast[1]](l[1], r[1]))
        return ('bin', ast[1], l, r)
    if k == 'asg':
        return ('asg', ast[1], fold(ast[2], consts))
    return ast


def fmt_ast(ast):
    k = ast[0]
    if k == 'c':
        return str(ast[1])
    if k == 's':
        return '"%s"' % ast[1]
    if k == 'v':
        return 'T%x(%d)' % (ast[1], ast[2])
    if k == 'vi':
        return 'V%x[%s]' % (ast[1], fmt_ast(ast[2]))
    if k == 'vk':
        return 'V%x(%d)[%s]' % (ast[1], ast[2], fmt_ast(ast[3]))
    if k == 'bin':
        return '(%s %s %s)' % (fmt_ast(ast[2]), ast[1], fmt_ast(ast[3]))
    return '%s = %s' % (fmt_ast(ast[1]), fmt_ast(ast[2]))


class VarMap:
    """Maps game variables onto ONScripter variables.

    V101[n] (n < 175)  -> %n            story flags, saved with the savegame
    V101[n] (n >= 175) -> %300...       persistent (global) variables
    V108[1500 + k]     -> %(400 + k)    CG / scene unlock flags (global)
    everything else    -> %500...       scratch values
    """
    LOCAL_LIMIT = 175

    def __init__(self):
        self.g = {}
        self.misc = {}

    def v101(self, n):
        if 0 <= n < self.LOCAL_LIMIT:
            return n
        return self.g.setdefault(('v101', n), 300 + len([k for k in self.g if k[0] == 'v101']))

    def v108(self, n):
        if 1500 <= n < 1600:
            return 400 + n - 1500
        return self.misc_var(('v108', n))

    def misc_var(self, key):
        return self.misc.setdefault(key, 500 + len(self.misc))

    def num(self, ast):
        k = ast[0]
        if k == 'vi' and ast[2][0] == 'c':
            n = ast[2][1]
            if ast[1] == 0x101:
                return '%%%d' % self.v101(n)
            if ast[1] == 0x108:
                return '%%%d' % self.v108(n)
            if ast[1] == 0x102:
                return '$%d' % n
        if k == 'v':
            return '%%%d' % self.misc_var(('v', ast[1], ast[2]))
        if k == 'vk' and ast[3][0] == 'c':
            return '%%%d' % self.misc_var(('vk', ast[1], ast[2], ast[3][1]))
        raise Unsupported('variable ' + fmt_ast(ast))


class Library:
    """Reads the lookup tables out of the shared library code."""

    def __init__(self, sc):
        self.sc = sc
        self.ins = sc.disasm(sc.hdr, sc.code_mid)
        self.idx = {i.off: k for k, i in enumerate(self.ins)}

    def func(self, label):
        k = self.idx[self.sc.labels[label]]
        e = k
        while self.ins[e].kind != 'ret':
            e += 1
        return k, e

    def first_string(self, k, limit=60):
        for i in self.ins[k:k + limit]:
            if i.kind == 'expr' and i.a[0] == 0x201:
                for it in i.a[1]:
                    if it[0] == 't' and it[1] == 0x105:
                        return self.sc.string(it[2])
            if i.kind in ('jmp', 'ret'):
                break
        return None

    def first_call(self, k, limit=20):
        for i in self.ins[k:k + limit]:
            if i.kind == 'calll':
                return i.a
        return None

    def case_group(self, k, e):
        res = []
        for i in self.ins[k:e]:
            if i.kind == 'case':
                res.append((i.a, i.b))
            elif res:
                break
        return res

    def table(self, label, getter):
        k, e = self.func(label)
        return {v: getter(self.idx[t]) for v, t in self.case_group(k, e)}

    def bg(self):
        return self.table(15, self.first_string)

    def bgm(self):
        return {v: s for v, s in self.table(31, self.first_string).items() if s}

    def chars(self):
        """char id -> (width, [file per expression])"""
        out = {}
        for ch, lab in self.table(18, self.first_call).items():
            k, e = self.func(lab)
            files = {}
            width = None
            for v, t in self.case_group(k, e):
                files[v] = self.first_string(self.idx[t])
                for i in self.ins[self.idx[t]:self.idx[t] + 12]:
                    if i.kind == 'expr':
                        a = parse_expr(self.sc, i.a)
                        if a[0] == 'asg' and a[1] == ('v', 0x103, 291) and a[2][0] == 'c':
                            width = a[2][1]
            out[ch] = (width, [files[v] for v in sorted(files)])
        return out

    def selects(self):
        """choice set id -> list of (row, column group) cells of select_mes"""
        k, e = self.func(9)
        res = {}
        for sid, t in self.case_group(k, e):
            n = None
            rows = {}
            cols = {}
            for i in self.ins[self.idx[t]:e]:
                if i.kind == 'jmp':
                    break
                if i.kind != 'expr':
                    continue
                a = fold(parse_expr(self.sc, i.a), {})
                if a[0] != 'asg':
                    continue
                lhs, rhs = a[1], a[2]
                if lhs == ('v', 0x10d, 28) and rhs[0] == 'c':
                    n = rhs[1]
                elif lhs[0] == 'vk' and lhs[2] in (32, 44) and lhs[3][0] == 'c':
                    (rows if lhs[2] == 32 else cols)[lhs[3][1]] = rhs
            if n is None:
                continue
            cells = []
            for j in range(n):
                r, c = rows.get(j), cols.get(j)
                if r is None or r[0] != 'c':
                    raise Unsupported('select layout %d' % sid)
                cells.append((r[1] // 34, c[1] // 204 if c and c[0] == 'c' else 0))
            res[sid] = cells
        return res


