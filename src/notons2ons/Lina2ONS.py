def lz_decode(src):
    ring = bytearray(2048)
    r = 0x7E8
    out = bytearray()
    n = len(src)
    i = 0
    flags = 0
    while True:
        flags >>= 1
        if not flags & 0x100:
            if i >= n:
                break
            flags = src[i] | 0xFF00
            i += 1
        if flags & 1:
            if i >= n:
                break
            c = src[i]
            i += 1
            out.append(c)
            ring[r] = c
            r = (r + 1) & 2047
        else:
            if i + 1 >= n:
                break
            b0 = src[i]
            b1 = src[i + 1]
            i += 2
            p = b0 | (b1 & 0xE0) << 3
            for _ in range((b1 & 0x1F) + 2):
                c = ring[p]
                p = (p + 1) & 2047
                out.append(c)
                ring[r] = c
                r = (r + 1) & 2047
    return bytes(out)


def xor_decode(src):
    return bytes(itertools.accumulate(src, operator.xor))


def decode(data, mode):
    if mode == 0:
        return data
    if mode == 1:
        return lz_decode(data)
    if mode == 2:
        return xor_decode(data)
    raise ValueError("unknown mode %d" % mode)


def extract_entry(args):
    path, base, name, stored, size_field, mode, offset, outdir = args
    with open(path, "rb") as f:
        f.seek(base + offset)
        data = f.read(stored)
    out = decode(data, mode)
    ok = mode != 1 or len(out) == size_field
    with open(os.path.join(outdir, name), "wb") as f:
        f.write(out)
    return name, ok


def extract_archive(archive, outdir, jobs=None):
    """Extract every entry of a KLZ5 archive. Returns (file_count, size_mismatch_count)."""
    os.makedirs(outdir, exist_ok=True)
    with open(archive, "rb") as f:
        head = f.read(16)
        if head[:4] != b"KLZ5":
            raise ValueError("not a KLZ5 archive: %s" % archive)
        count = struct.unpack_from("<I", head, 4)[0]
        table = f.read(52 * count)
    base = 16 + 52 * count
    tasks = []
    for i in range(count):
        e = table[52 * i:52 * (i + 1)]
        name = e[:32].split(b"\0")[0].decode("ascii")
        stored, size_field, mode, offset, _ = struct.unpack_from("<5I", e, 32)
        tasks.append((archive, base, name, stored, size_field, mode, offset, outdir))
    bad = 0
    with ProcessPoolExecutor(jobs or os.cpu_count()) as ex:
        for name, ok in ex.map(extract_entry, tasks, chunksize=4):
            if not ok:
                bad += 1
                # print("size mismatch:", name)
                logging.error("size mismatch: %s", name)
    return count, bad


def decode_svs(b):
    if b[:4] != b"SVS1":
        raise ValueError("not SVS1")
    mode, hdr, _, clen = struct.unpack_from("<4I", b, 0x10)
    total = struct.unpack_from("<I", b, 0xC)[0]
    if mode == 0:
        return b
    if mode != 1:
        raise ValueError("unknown mode %d" % mode)
    payload = lz_decode(b[hdr:hdr + clen])
    if len(payload) != total - hdr:
        raise ValueError("size mismatch")
    head = bytearray(b[:hdr])
    struct.pack_into("<I", head, 0x10, 0)
    return bytes(head) + payload


def export_text(b):
    pool = struct.unpack_from("<I", b, 8)[0]
    lines = []
    for s in b[pool:].split(b"\0"):
        if s:
            lines.append(s.decode("cp932", "replace").replace("\r", "\\r").replace("\n", "\\n"))
    return lines


def decode_dir(src, dec_dir, txt_dir):
    """Decode every .spr in src. Returns the number of files processed."""
    os.makedirs(dec_dir, exist_ok=True)
    os.makedirs(txt_dir, exist_ok=True)
    count = 0
    for fn in sorted(os.listdir(src)):
        if not fn.lower().endswith(".spr"):
            continue
        with open(os.path.join(src, fn), "rb") as f:
            full = decode_svs(f.read())
        with open(os.path.join(dec_dir, fn), "wb") as f:
            f.write(full)
        with open(os.path.join(txt_dir, fn[:-4] + ".txt"), "w", encoding="utf-8", newline="\r\n") as f:
            f.write("\n".join(export_text(full)) + "\n")
        count += 1
    return count


def _crc_table():
    table = []
    for i in range(256):
        r = i << 24
        for _ in range(8):
            r = ((r << 1) ^ 0x04C11DB7) & 0xFFFFFFFF if r & 0x80000000 else (r << 1) & 0xFFFFFFFF
        table.append(r)
    return table


_CRC = _crc_table()


def ogg_crc(data):
    c = 0
    for x in data:
        c = ((c << 8) & 0xFFFFFFFF) ^ _CRC[(c >> 24) ^ x]
    return c


def verify_ogg(d):
    pos = 0
    while pos < len(d):
        if d[pos:pos + 4] != b"OggS" or pos + 27 > len(d):
            return False
        nseg = d[pos + 26]
        size = 27 + nseg + sum(d[pos + 27:pos + 27 + nseg])
        page = bytearray(d[pos:pos + size])
        stored = struct.unpack_from("<I", page, 22)[0]
        page[22:26] = b"\0\0\0\0"
        if len(page) != size or ogg_crc(page) != stored:
            return False
        pos += size
    return True


def kog_to_ogg(data, verify=False):
    if data[:4] != b"KOGG":
        raise ValueError("not a KOGG file")
    header_size = struct.unpack_from("<I", data, 4)[0]
    ogg = data[header_size:]
    if ogg[:4] != b"OggS":
        raise ValueError("no Ogg stream after the KOGG header")
    if verify and not verify_ogg(ogg):
        raise ValueError("Ogg page/CRC check failed")
    return ogg


def convert_ogg(files, outdir, verify=False):
    """Convert .kog files to .ogg. Returns (converted, failed)."""
    os.makedirs(outdir, exist_ok=True)
    failed = 0
    for path in files:
        try:
            with open(path, "rb") as f:
                ogg = kog_to_ogg(f.read(), verify)
        except ValueError as e:
            failed += 1
            # print("%s: %s" % (path, e), file=sys.stderr)
            logging.error("%s: %s", path, e)
            continue
        out = os.path.join(outdir, os.path.splitext(os.path.basename(path))[0] + ".ogg")
        with open(out, "wb") as f:
            f.write(ogg)
    return len(files) - failed, failed


HEADER = struct.Struct("<4sIIIIIIIQII")


RECORD = struct.Struct("<6I")


class Mov:
    def __init__(self, data):
        if len(data) < HEADER.size or data[:4] != b"MOV1":
            raise ValueError("not a MOV1 file")
        (_, _, count, fps, _, self.width, self.height, _, size, tracks, base) = HEADER.unpack_from(data, 0)
        if size != len(data) or tracks != 2 or not count or not fps:
            raise ValueError("unexpected header (size %d, %d tracks, %d frames)" % (size, tracks, count))
        if HEADER.size + RECORD.size * (count + 1) > len(data):
            raise ValueError("truncated index")
        self.fps = fps
        recs = [RECORD.unpack_from(data, HEADER.size + RECORD.size * i) for i in range(count + 1)]
        self.frames = []
        for i, (idx, n, _, codec, off, _) in enumerate(recs[:-1]):
            if idx != i or codec != 2 or base + off + n > len(data) or data[base + off:base + off + 2] != b"\xff\xd8":
                raise ValueError("bad video record %d" % i)
            self.frames.append(data[base + off:base + off + n])
        _, n, _, _, off, _ = recs[-1]
        if base + off + n > len(data):
            raise ValueError("bad audio record")
        self.audio = kog_to_ogg(data[base + off:base + off + n])


def output_size(width, height, max_width):
    """Scale down (never up) to max_width, keeping the aspect ratio; both sides even."""
    if width > max_width:
        height = height * max_width // width
        width = max_width
    return width & ~1, height & ~1


def convert_file(args):
    src, dst, max_width, quality, ffmpeg = args
    with open(src, "rb") as f:
        mov = Mov(f.read())
    w, h = output_size(mov.width, mov.height, max_width)
    os.makedirs(os.path.dirname(dst) or ".", exist_ok=True)
    tmp = dst + ".tmp.mpg"
    with tempfile.TemporaryDirectory() as td:
        ogg = os.path.join(td, "audio.ogg")
        with open(ogg, "wb") as f:
            f.write(mov.audio)
        cmd = [ffmpeg, "-v", "error", "-y",
               "-f", "image2pipe", "-c:v", "mjpeg", "-framerate", str(mov.fps), "-i", "-",
               "-i", ogg,
               "-vf", "format=rgb24,colorchannelmixer=rr=0:rb=1:br=1:bb=0,"
                      "scale=%d:%d:flags=lanczos:out_range=tv,fps=30,format=yuv420p" % (w, h),
               "-c:v", "mpeg1video", "-qscale:v", str(quality), "-g", "15", "-bf", "0",
               "-c:a", "mp2", "-b:a", "128k", "-ar", "44100", "-ac", "2",
               "-shortest", "-f", "mpeg", tmp]
        p = subprocess.Popen(cmd, stdin=subprocess.PIPE, stderr=subprocess.PIPE)
        try:
            for frame in mov.frames:
                p.stdin.write(frame)
            p.stdin.close()
        except BrokenPipeError:
            pass
        err = p.stderr.read().decode("utf-8", "replace")
        if p.wait() != 0:
            raise RuntimeError(err.strip() or "ffmpeg failed")
    os.replace(tmp, dst)
    return os.path.getsize(dst)


def convert_movies(files, outdir, max_width=400, quality=3, ffmpeg="ffmpeg", jobs=1):
    """Convert .mov files to .mpg. Returns (converted, failed)."""
    os.makedirs(outdir, exist_ok=True)
    tasks = [(p, os.path.join(outdir, os.path.splitext(os.path.basename(p))[0] + ".mpg"), max_width, quality, ffmpeg)
             for p in files]
    failed = 0
    with ProcessPoolExecutor(max_workers=max(1, min(jobs, len(tasks) or 1))) as pool:
        futures = [(t, pool.submit(convert_file, t)) for t in tasks]
        for t, fut in futures:
            try:
                size = fut.result()
                # print("%s -> %s (%.1f MB)" % (os.path.basename(t[0]), os.path.basename(t[1]), size / 1048576), flush=True)
            except (ValueError, RuntimeError, OSError) as e:
                failed += 1
                # print("%s: %s" % (t[0], e), file=sys.stderr)
                logging.error("%s: %s", t[0], e)
    return len(tasks) - failed, failed


def find_ffmpeg(path=None):
    return shutil.which(path or "ffmpeg")


def find_files(directory, ext):
    return [os.path.join(directory, f) for f in sorted(os.listdir(directory)) if f.lower().endswith(ext)]


