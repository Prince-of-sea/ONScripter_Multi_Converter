def extract_resource(values: dict, values_ex: dict, pre_converted_dir: Path):
    input_dir = Path(values['input_dir']).resolve()
    out = Path(pre_converted_dir).resolve() / 'unpacked'
    jobs = values_ex.get('num_workers', os.cpu_count() or 1)
    if not isinstance(jobs, int) or isinstance(jobs, bool) or jobs < 1:
        raise ValueError('num_workers must be a positive integer')
    width = values_ex.get('movie_width', 400)
    if not isinstance(width, int) or isinstance(width, bool) or width < 2:
        raise ValueError('movie_width must be an integer of at least 2')
    archives = [input_dir / 'pack' / (name + '.klz')
                for name in ('dat', 'music', 'script', 'voice', 'wav')]
    for archive in archives:
        if not archive.is_file():
            raise FileNotFoundError(archive)
    video = input_dir / 'video'
    if not video.is_dir():
        raise FileNotFoundError(video)
    movies = find_files(str(video), '.mov')
    if not movies:
        raise FileNotFoundError('no MOV1 movies in %s' % video)
    ffmpeg = find_ffmpeg(values_ex.get('ffmpeg'))
    if not ffmpeg:
        raise FileNotFoundError('ffmpeg was not found; install ffmpeg or specify values_ex["ffmpeg"]')
    out.mkdir(parents=True, exist_ok=True)
    for archive in archives:
        problems = process(str(archive), str(out), jobs, True)
        if problems:
            raise RuntimeError('%s: %d extraction/conversion errors' % (archive, problems))
    _, failed = convert_movies(movies, str(out / 'movie'), width, 3, ffmpeg, jobs)
    if failed:
        raise RuntimeError('%d movie conversions failed' % failed)


