def _split_arguments(source: str) -> list[str]:
    if not source.strip():
        return []
    parts: list[str] = []
    start = 0
    quote = False
    escaped = False
    for index, char in enumerate(source):
        if escaped:
            escaped = False
        elif char == "\\" and quote:
            escaped = True
        elif char == "'":
            quote = not quote
        elif char == "," and not quote:
            parts.append(source[start:index].strip())
            start = index + 1
    parts.append(source[start:].strip())
    return parts


def _parse_argument(source: str) -> str | int | None:
    if len(source) >= 2 and source[0] == "'" and source[-1] == "'":
        value = source[1:-1]
        return value.replace("\\'", "'").replace("\\\\", "\\")
    try:
        return int(source, 0)
    except ValueError:
        return None


@functools.lru_cache(maxsize=None)
def _rx(pattern: str, flags: int = 0) -> re.Pattern[str]:
    return re.compile(pattern, flags)


def _parse_call(line: str) -> tuple[str, list[str | int | None]] | None:
    match = _rx(r"^(call|syscall)<\$([0-9a-f]+)(?:,\s*0)?>\s*(?:\((.*)\))?\s*$", re.IGNORECASE).match(
        line.strip()
    )
    if not match:
        return None
    args = match.group(3) or ""
    return match.group(2).lower(), [_parse_argument(arg) for arg in _split_arguments(args)]


def _png_size(path: Path) -> tuple[int, int] | None:
    try:
        with open(path, "rb") as file:
            header = file.read(24)
    except OSError:
        return None
    if header[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    return struct.unpack(">II", header[16:24])


