@functools.lru_cache(maxsize=None)
def _mjo_key() -> bytes:
    table = []
    for value in range(256):
        for _ in range(8):
            value = (value >> 1) ^ 0xEDB88320 if value & 1 else value >> 1
        table.append(value)
    return struct.pack("<256I", *table)


def patch_unknown_ctrl(data: bytes) -> bytes | None:
    """暗号化された .mjo の ctrl "z" を、何もしない ctrl "r"（ルビ終了）に置き換える。該当が無ければ None。

    バイトコードは CRC32 テーブルとの XOR で暗号化されているため、復号して位置を探し、1バイトだけ書き換える。
    """
    k = _cfg()
    if data[: len(k.mjo_signature)] != k.mjo_signature:
        return None
    entries = struct.unpack_from("<I", data, 24)[0]
    size_offset = 28 + 8 * entries
    start = size_offset + 4
    size = struct.unpack_from("<I", data, size_offset)[0]
    key = _mjo_key()
    code = bytes(byte ^ key[index & 0x3FF] for index, byte in enumerate(data[start : start + size]))
    position = code.find(k.unknown_ctrl)
    if position < 0:
        return None
    patched = bytearray(data)
    target = position + len(k.unknown_ctrl) - 2
    patched[start + target] ^= ord("z") ^ ord("r")
    return bytes(patched)


def merge_sjs(mjs_text: str, sjs_text: str) -> str:
    """mjdisasm は文字列を .sjs に分けて出力するため、.mjs の `#res<NNNN>` に戻して1本にする。

    単独行の `#res` は本文なので、`名前「台詞」` を名前行と台詞行に分け、`\\n` は `br` にする。
    引数の `#res` は文字列リテラルにする（エスケープはしない）。
    """
    strings: dict[str, str] = {}
    entry = _rx(r"^<(\d{4})> (.*)$")
    for line in sjs_text.splitlines():
        match = entry.match(line)
        if match:
            text = match.group(2)
            # 先頭・末尾の空白は `\ `（先頭）、`\`（末尾）で保持される
            if text.startswith("\\ "):
                text = text[1:]
            if text.endswith("\\") and not text.endswith("\\\\"):
                text = text[:-1] + " "
            strings[match.group(1)] = text

    def quoted(match: re.Match[str]) -> str:
        return "'" + strings.get(match.group(1), "") + "'"

    merged: list[str] = []
    whole_line = _rx(r"^(\s*)#res<(\d{4})>\s*$")
    inline = _rx(r"#res<(\d{4})>")
    for line in mjs_text.splitlines():
        whole = whole_line.match(line) if "#res<" in line else None
        if whole:
            rows = strings.get(whole.group(2), "").split("\\n")
            speaker = next((i for i, row in enumerate(rows) if row), None)
            for number, row in enumerate(rows):
                if number:
                    merged.append("br")
                name, bracket, speech = row.partition("「") if number == speaker else (row, "", "")
                if bracket and name:
                    merged.append("'" + name + "'")
                    row = bracket + speech
                if row:
                    merged.append("'" + row + "'")
            continue
        merged.append(inline.sub(quoted, line) if "#res<" in line else line)
    return "\n".join(merged) + "\n"


