def _png_rgba(width: int, height: int, pixel: tuple[int, int, int, int]) -> bytes:
    def chunk(tag: bytes, data: bytes) -> bytes:
        return (
            struct.pack(">I", len(data))
            + tag
            + data
            + struct.pack(">I", zlib.crc32(tag + data) & 0xFFFFFFFF)
        )

    row = b"\x00" + bytes(pixel) * width
    return (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0))
        + chunk(b"IDAT", zlib.compress(row * height, 9))
        + chunk(b"IEND", b"")
    )


def _zenkaku(text: str) -> str:
    # 画面に表示する文字は半角を使わない（英数字・記号・空白を全角にする）
    return "".join(
        "\u3000" if char == " " else chr(ord(char) + 0xFEE0) if "!" <= char <= "~" else char
        for char in text
    )


