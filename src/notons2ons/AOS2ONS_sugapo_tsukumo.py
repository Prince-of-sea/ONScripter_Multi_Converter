def _archive_records(archive: Path) -> list[tuple[str, int, int]]:
    return _read_aos_index(archive)


def _variable_aliases(
    script_sources: dict[str, str], internal_variable_count: int = 0
) -> tuple[str, list[int]]:
    variables = {
        match.group(1)
        for source in script_sources.values()
        for match in re.finditer(r"%([A-Za-z_][A-Za-z0-9_]*)", source)
    }
    occupied = {
        int(match.group(1))
        for source in script_sources.values()
        for match in re.finditer(r"%(\d+)", source)
    }
    occupied.update((*range(100, 105), *range(130, 151)))
    available = [number for number in range(100, 1000) if number not in occupied]
    if len(variables) + internal_variable_count > len(available):
        raise ValueError("ONScripterで割り当て可能な数を超える名前付き数値変数があります。")
    internal_variables = (
        available[-internal_variable_count:] if internal_variable_count else []
    )
    alias_numbers = available[:-internal_variable_count] if internal_variable_count else available
    aliases = "\n".join(
        f"numalias {name},{number}"
        for name, number in zip(sorted(variables, key=str.casefold), alias_numbers)
    )
    return aliases, internal_variables


def _conditional_block_span(
    lines: list[str], condition: str
) -> tuple[int, int, int | None]:
    block_stack: list[str] = []
    block_start: int | None = None
    else_branch: int | None = None
    normalized_condition = re.sub(r"\s+", "", condition).casefold()

    for index, raw_line in enumerate(lines):
        line = raw_line.strip()
        if not line or line.startswith("#") or line.startswith("::"):
            continue
        if "\t#" in line:
            line = line.split("\t#", 1)[0].rstrip()
        elif " #" in line:
            line = line.split(" #", 1)[0].rstrip()
        directive = re.match(r"^\^([A-Za-z_]+)\s*(?:\((.*)\))?$", line)
        if directive is None:
            continue
        command = directive.group(1).lower()
        argument = re.sub(r"\s+", "", (directive.group(2) or "")).casefold()

        if block_start is None:
            if command == "if" and argument == normalized_condition:
                block_start = index
                block_stack.append("if")
            continue
        if command == "if":
            block_stack.append("if")
        elif command == "sw":
            block_stack.append("switch")
        elif command == "else" and block_stack == ["if"]:
            else_branch = index
        elif command == "endi":
            if block_stack and block_stack[-1] == "switch":
                continue
            if block_stack and block_stack[-1] == "if":
                block_stack.pop()
            if not block_stack:
                return block_start, index, else_branch
        elif command == "ends" and block_stack and block_stack[-1] == "switch":
            block_stack.pop()

    raise ValueError(f"main.scr の条件分岐を特定できません: {condition}")


def _product_main_source(source: str) -> str:
    lines = source.splitlines()
    gate_start, gate_end, product_branch = _conditional_block_span(
        lines, "%TAIKEN_FLAG1==1"
    )
    if product_branch is None:
        raise ValueError("main.scr の製品版シナリオ分岐を特定できません。")
    product_lines = (
        lines[:gate_start]
        + lines[product_branch + 1 : gate_end]
        + lines[gate_end + 1 :]
    )
    debug_start, debug_end, _ = _conditional_block_span(
        product_lines, "%DEBUG_FLAG==1"
    )
    return "\n".join(product_lines[:debug_start] + product_lines[debug_end + 1 :])


def _detect_title(script_sources: dict[str, str]) -> str:
    # 展開したシナリオの先頭コメント「# タイトル　：～」からどの作品かを判別する
    for source in script_sources.values():
        match = re.search(r"(?m)^#\s*タイトル\s*[：:]\s*(.+)$", source)
        if match is None:
            continue
        if "恋する少女" in match.group(1):
            return "koi"
        if "ツクモノツキ" in match.group(1):
            return "tsukumo"
        raise ValueError(f"未対応のタイトルです: {match.group(1).strip()}")
    raise ValueError("scr.aos からタイトル表記を持つシナリオを見つけられませんでした。")


def _drop_trial_branches(source: str) -> str:
    # 体験版フラグ(==1)の ^if ブロックを削除する。^else があればそちらの内容を残す
    lines = source.splitlines()
    flags = ("TAIKEN_FLAG1", "TAIKEN_FLAG2", "COMIKE_FLAG1", "TECK_FLAG", "PUSH_FLAG")
    for flag in flags:
        pattern = re.compile(rf"(?i)^\s*\^if\(\s*%{flag}\s*==\s*1\s*\)")
        while any(pattern.match(line) for line in lines):
            start, end, else_branch = _conditional_block_span(
                lines, f"%{flag}==1"
            )
            kept = lines[else_branch + 1 : end] if else_branch is not None else []
            lines = lines[:start] + kept + lines[end + 1 :]
    return "\n".join(lines)


def _convert_image_job(job: tuple[Path, Path, str, int, int, str]) -> None:
    # ProcessPoolExecutor に渡すため、関数内クロージャではなくトップレベルに置く。
    archive, destination, archive_name, offset, size, extension = job
    data = _read_entry(archive, offset, size)
    if extension == ".cmp":
        data = _decode_huffman(data)
    if extension in (".abm", ".cmp"):
        image = _decode_abm(data)
    else:
        from PIL import Image

        import io

        image = Image.open(io.BytesIO(data))
        image.load()
    image.save(
        destination / f"{Path(archive_name).stem}.png",
        format="PNG",
        compress_level=1,
    )


def extract_resource(values: dict[str, Any], values_ex: dict[str, Any], pre_converted_dir: Path) -> dict[str, Any]:
    input_dir = Path(values["input_dir"])
    output_dir = Path(pre_converted_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    duplicate_paths: set[str] = set()
    copied_paths: set[str] = set()
    script_sources: dict[str, str] = {}
    audio_names: dict[str, set[str]] = {}

    for archive_name, output_name in (
        ("bgm.aos", "bgm"),
        ("cv.aos", "voice"),
        ("se.aos", "se"),
    ):
        archive = input_dir / archive_name
        destination = output_dir / output_name
        destination.mkdir(parents=True, exist_ok=True)
        records = _archive_records(archive)
        audio_names[output_name] = {Path(name).stem.casefold() for name, _, _ in records}
        for name, offset, size in records:
            target = destination / Path(name).name
            relative = str(target.relative_to(output_dir)).casefold()
            if relative in copied_paths:
                duplicate_paths.add(relative)
            copied_paths.add(relative)
            target.write_bytes(_read_entry(archive, offset, size))

    script_archive = input_dir / "scr.aos"
    script_paths: set[str] = set()
    for name, offset, size in _archive_records(script_archive):
        if not name.lower().endswith(".scr"):
            continue
        if name.casefold() in script_paths:
            duplicate_paths.add(f"scr\\{name.casefold()}")
        script_paths.add(name.casefold())
        decoded = _decode_huffman(_read_entry(script_archive, offset, size))
        source = decoded.decode("cp932")
        if Path(name).stem.casefold() == "main":
            source = _product_main_source(source)
        script_sources[Path(name).name] = source

    title = _detect_title(script_sources)
    if title == "koi":
        # 体験版・デバッグ・タイトル/おまけ画面・立ち絵確認用のスクリプトは製品版の本編に不要
        script_sources = {
            name: source
            for name, source in script_sources.items()
            if not re.match(
                r"(?i)^(tai|db_menu|title|mode_h|main_har|start$|btnsel|init_spr|macro|wnd_nov|t[ab]\d\d[a-z]$)",
                Path(name).stem,
            )
        }
        script_sources = {
            name: _drop_trial_branches(source)
            for name, source in script_sources.items()
        }
    image_archive = input_dir / "grp.aos"
    image_destination = output_dir / "image"
    image_destination.mkdir(parents=True, exist_ok=True)
    images: dict[str, tuple[int, int, str]] = {}
    for name, offset, size in _archive_records(image_archive):
        extension = Path(name).suffix.lower()
        if extension not in (".bmp", ".abm", ".cmp"):
            continue
        output_name = f"{Path(name).stem}.png"
        target = image_destination / output_name
        relative = str(target.relative_to(output_dir)).casefold()
        if relative in copied_paths:
            duplicate_paths.add(relative)
        copied_paths.add(relative)
        images[Path(name).stem.casefold()] = (offset, size, extension)
    resource_names = {"image": set(images), **audio_names}

    # 変換コストの大きい(=圧縮サイズが大きい)ものから投入して負荷を均す
    image_jobs = [
        (image_archive, image_destination, name, offset, size, extension)
        for name, (offset, size, extension) in sorted(
            images.items(), key=lambda item: -item[1][1]
        )
    ]
    with concurrent.futures.ThreadPoolExecutor() as executor:
        for _ in executor.map(_convert_image_job, image_jobs):
            pass

    movie_source = input_dir / "movie"
    if movie_source.exists():
        shutil.copytree(movie_source, output_dir / "movie", dirs_exist_ok=True)

    from PIL import Image

    def join_button(name: str) -> None:
        # 縦に3段並んだボタン画像を、ONScripterのセル形式(横並び)に組み直す
        path = image_destination / f"{name}.png"
        with Image.open(path) as source_image:
            cells = source_image.convert("RGBA")
        cell_height = cells.height // 3
        joined = Image.new("RGBA", (cells.width * 3, cell_height))
        for index in range(3):
            joined.paste(
                cells.crop((0, index * cell_height, cells.width, (index + 1) * cell_height)),
                (index * cells.width, 0),
            )
        joined.save(path, format="PNG")

    with concurrent.futures.ThreadPoolExecutor() as executor:
        for _ in executor.map(
            join_button, ("btn_play", "btn_load", "btn_omake", "btn_config", "btn_end")
        ):
            pass

    # 窓枠は立ち絵・名前より前面に出ないよう msgwnd1 をスプライトで描くため、本物の窓は透明にする
    Image.new("RGBA", (1024, 170) if title == "koi" else (872, 168), (0, 0, 0, 0)).save(
        image_destination / "tw.png", format="PNG"
    )

    translated = []

    script_names = {Path(name).stem.casefold() for name in script_sources}
    sprite_channels = sorted(
        {
            int(match.group(1))
            for source in script_sources.values()
            for match in re.finditer(
                r"(?im)^\s*chon\s*\(\s*(\d+)\s*,", source
            )
        }
        | (
            {
                int(match.group(1))
                for source in script_sources.values()
                for match in re.finditer(
                    r"(?im)^\s*efex\s*\(\s*(\d+)\s*,\s*1[123]\s*,", source
                )
            }
            if title == "koi"
            else set()
        )
    )
    variable_alias_text, internal_variables = _variable_aliases(
        script_sources, len(sprite_channels) * 4
    )
    sprite_position_variables = {
        channel: (
            internal_variables[index * 4],
            internal_variables[index * 4 + 1],
            internal_variables[index * 4 + 2],
            internal_variables[index * 4 + 3],
        )
        for index, channel in enumerate(sprite_channels)
    }
    label_owners: dict[str, list[str]] = {}
    for name, source in script_sources.items():
        for line in source.splitlines():
            label = line.strip()
            if label.startswith(":") and not label.startswith("::"):
                label_owners.setdefault(label[1:].strip().casefold(), []).append(
                    f"*l_{Path(name).stem.casefold()}_{re.sub(r'[^A-Za-z0-9_]', '_', label[1:].strip()).casefold()}"
                )
    global_labels = {
        label: owners[0]
        for label, owners in label_owners.items()
        if len(owners) == 1
    }
    speaker_ids: dict[str, int] = {}
    for name in script_sources:
        stem = Path(name).stem.casefold()
        translated_name = f"*s_{stem}\n" + _translate_script(
            name,
            script_sources[name],
            script_names,
            global_labels,
            resource_names,
            sprite_position_variables,
            speaker_ids,
            title,
        )
        translated.append(translated_name)
    choff_channels = {
        int(match.group(1))
        for source in script_sources.values()
        for match in re.finditer(r"(?im)^\s*choff\s*\(\s*(\d+)\s*\)", source)
    }
    translated.append(
        _sprite_subroutines(
            sprite_position_variables, choff_channels, speaker_ids, title
        )
    )

    position_initialization = "\n".join(
        f"mov %{x_variable},512\n"
        f"mov %{y_variable},0\n"
        f"mov %{y_center_variable},0\n"
        f"mov %{active_variable},0"
        for (
            x_variable,
            y_variable,
            y_center_variable,
            active_variable,
        ) in sprite_position_variables.values()
    )
    runtime = (
        default_txt_koi(audio_names["se"])
        if title == "koi"
        else default_txt(audio_names["se"])
    ).replace(
        "savenumber 11\n",
        "savenumber 11\n" + variable_alias_text + "\n",
    )
    if position_initialization:
        runtime = runtime.replace(
            "gosub *s_init_var\n",
            f"gosub *s_init_var\n{position_initialization}\n",
            1,
        )
    script_text = runtime + "\n" + "\n".join(translated)
    defined_labels = set(re.findall(r"^\*([A-Za-z0-9_]+)\s*$", script_text, re.MULTILINE))
    transfer_targets = set(
        re.findall(r"\b(?:goto|gosub)\s+\*([A-Za-z0-9_]+)", script_text)
    )
    unresolved_targets = sorted(transfer_targets - defined_labels)
    if unresolved_targets:
        script_text += "\n" + "\n".join(
            f"*{target}\n; source target was not present in scr.aos\nreturn"
            for target in unresolved_targets
        )
        # warnings.warn(
        #     f"scr.aos に転送先がないスクリプト参照を {len(unresolved_targets)} 件、復帰用ラベルに置き換えました。"
        #     f" 例: {', '.join(unresolved_targets[:10])}",
        #     RuntimeWarning,
        #     stacklevel=2,
        # )
    missing_resources = sorted(
        set(
            re.findall(
                r"; missing (?:image|BGM|SE|voice) resource: (.+)",
                script_text,
            )
        )
    )
    # if missing_resources:
    #     warnings.warn(
    #         f"アーカイブにない画像/音声参照が {len(missing_resources)} 種あります。"
    #         f" 例: {', '.join(missing_resources[:10])}",
    #         RuntimeWarning,
    #         stacklevel=2,
    #     )
    (output_dir / "0.txt").write_bytes(
        re.sub(r"(?m)^; .*\n", "", script_text).encode("cp932")
    )

    for runtime_name in ("ONScripter.exe", "onsyuri_v0.7.4_amd64_win.exe", "default.ttf"):
        runtime_file = output_dir / runtime_name
        if not runtime_file.exists():
            test_file = Path(__file__).resolve().parent / "testspace" / runtime_name
            if test_file.exists():
                shutil.copy2(test_file, runtime_file)
    # if duplicate_paths:
    #     warnings.warn(
    #         "同名リソースを後のアーカイブ項目で上書きしました: "
    #         + ", ".join(sorted(duplicate_paths)),
    #         RuntimeWarning,
    #         stacklevel=2,
    #     )
    return {
        "duplicate_paths": sorted(duplicate_paths),
        "unresolved_targets": unresolved_targets,
        "missing_resources": missing_resources,
    }


def main(values: dict[str, Any] | None = None, values_ex: dict[str, Any] | None = None, pre_converted_dir: Path | None = None,) -> None:
    workspace = Path(__file__).resolve().parent
    values = {} if values is None else values
    input_dir = Path(values.get("input_dir", workspace / "game_file" / "恋する少女と想いのキセキ"))
    output_dir = pre_converted_dir or Path(values.get("pre_converted_dir", workspace / "testspace_koi"))
    if not input_dir.is_dir():
        raise FileNotFoundError(f"ゲームデータのフォルダが見つかりません: {input_dir}")
    extract_resource({"input_dir": input_dir}, values_ex or {}, output_dir)

