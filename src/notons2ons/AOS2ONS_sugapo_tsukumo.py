def _decode_huffman(packed: bytes) -> bytes:
    if len(packed) < 5:
        raise ValueError("AOS内のハフマンデータが短すぎます。")
    unpacked_size = struct.unpack_from("<I", packed)[0]
    source = packed[4:]
    source_pos = 0
    bit_pos = 0
    left: list[int] = []
    right: list[int] = []

    def get_bits(count: int) -> int:
        nonlocal source_pos, bit_pos
        value = 0
        for _ in range(count):
            if source_pos >= len(source):
                raise EOFError("AOS内のハフマンデータが途中で終わりました。")
            value = (value << 1) | ((source[source_pos] >> (7 - bit_pos)) & 1)
            bit_pos += 1
            if bit_pos == 8:
                bit_pos = 0
                source_pos += 1
        return value

    def create_tree() -> int:
        if get_bits(1):
            node = 256 + len(left)
            if node >= 512:
                raise ValueError("AOS内のハフマンツリーが不正です。")
            left.append(0)
            right.append(0)
            left[node - 256] = create_tree()
            right[node - 256] = create_tree()
            return node
        return get_bits(8)

    root = create_tree()
    output = bytearray(unpacked_size)
    for index in range(unpacked_size):
        node = root
        while node >= 256:
            branch = get_bits(1)
            node = right[node - 256] if branch else left[node - 256]
        output[index] = node
    return bytes(output)


def _read_aos_index(archive: Path) -> list[tuple[str, int, int]]:
    with archive.open("rb") as source:
        header = source.read(12)
        if len(header) != 12 or struct.unpack_from("<I", header)[0] != 0:
            raise ValueError(f"{archive.name} は対応するAOSv2アーカイブではありません。")
        base_offset, index_size = struct.unpack_from("<II", header, 4)
        if index_size % 0x28:
            raise ValueError(f"{archive.name} のインデックスサイズが不正です。")
        source.seek(0x111)
        index = source.read(index_size)
        if len(index) != index_size:
            raise EOFError(f"{archive.name} のインデックスが途中で終わりました。")
        entries = []
        for index_offset in range(0, index_size, 0x28):
            record = index[index_offset : index_offset + 0x28]
            name_data = record[:0x20].split(b"\0", 1)[0]
            if not name_data:
                raise ValueError(f"{archive.name} に空のファイル名があります。")
            name = name_data.decode("cp932")
            relative_offset, size = struct.unpack_from("<II", record, 0x20)
            offset = base_offset + relative_offset
            if offset + size > archive.stat().st_size:
                raise ValueError(f"{archive.name} 内の {name} の位置が不正です。")
            if Path(name).is_absolute() or ".." in Path(name).parts:
                raise ValueError(f"{archive.name} 内に不正なパスがあります: {name}")
            entries.append((name, offset, size))
        return entries


def _read_entry(archive: Path, offset: int, size: int) -> bytes:
    with archive.open("rb") as source:
        source.seek(offset)
        data = source.read(size)
    if len(data) != size:
        raise EOFError(f"{archive.name} 内のデータが途中で終わりました。")
    return data


def _unpack_abm32(data: bytes, position: int, total: int) -> bytes:
    # 色(3byte/pixel)とアルファ(1byte/pixel)を別々のバッファに溜め、最後にnumpyでRGBAへ合成する。
    # 1バイトずつのループとcomponentカウンタを廃し、リテラルはスライスコピーで処理する。
    import numpy as np

    pixel_count = total // 4
    color_total = pixel_count * 3
    color = bytearray(color_total)
    alpha = bytearray(pixel_count)
    data_length = len(data)
    index = 0  # 色バイト列上の書き込み位置 (旧実装の destination/component に相当)

    while index < color_total:
        if position >= data_length:
            destination = 4 * (index // 3) + index % 3
            raise EOFError(
                f"ABMの32bit RLEデータが途中で終わりました (出力 {destination}/{total} バイト)。"
            )
        value = data[position]
        position += 1
        if value == 0:
            if position >= data_length:
                raise EOFError("ABMの32bit RLEスキップ長がありません。")
            count = data[position]
            position += 1
            if count > total - (4 * (index // 3) + index % 3):
                raise ValueError("ABMの32bit RLEスキップ長が画像の範囲を超えています。")
            index += count
        elif value == 0xFF:
            if position >= data_length:
                raise EOFError("ABMの32bit RLEリテラル長がありません。")
            count = data[position]
            position += 1
            copied = min(count, color_total - index)
            available = data_length - position
            if copied > available:
                index += max(available, 0)
                destination = 4 * (index // 3) + index % 3
                raise EOFError(
                    f"ABMの32bit RLEリテラルが途中で終わりました (出力 {destination}/{total} バイト)。"
                )
            if copied > 0:
                color[index : index + copied] = data[position : position + copied]
                first = index // 3
                completed = (index + copied - 3) // 3 - first + 1
                if completed > 0:
                    alpha[first : first + completed] = b"\xff" * completed
                position += copied
                index += copied
        else:
            if position >= data_length:
                raise EOFError("ABMの32bit RLEリテラルがありません。")
            color[index] = data[position]
            position += 1
            if index % 3 == 2:
                alpha[index // 3] = value
            index += 1

    output = np.zeros((pixel_count, 4), dtype=np.uint8)
    output[:, :3] = np.frombuffer(color, dtype=np.uint8).reshape(pixel_count, 3)
    output[:, 3] = np.frombuffer(alpha, dtype=np.uint8)
    return output.tobytes()


def _unpack_abm24(data: bytes, position: int, total: int, end: int | None = None) -> bytes:
    output = bytearray(total)
    destination = 0
    end = len(data) if end is None else end
    while destination < total:
        if position >= end:
            raise EOFError(
                f"ABMの24bit RLEデータが途中で終わりました (出力 {destination}/{total} バイト)。"
            )
        value = data[position]
        position += 1
        if value == 0:
            if position >= end:
                raise EOFError("ABMの24bit RLEスキップ長がありません。")
            count = data[position]
            position += 1
            if count > total - destination:
                raise ValueError("ABMの24bit RLEスキップ長が画像の範囲を超えています。")
            destination += count
        elif value == 0xFF:
            if position >= end:
                raise EOFError("ABMの24bit RLEリテラル長がありません。")
            count = data[position]
            position += 1
            copied = min(count, total - destination)
            if position + copied > end:
                raise EOFError("ABMの24bit RLEリテラルが途中で終わりました。")
            output[destination : destination + copied] = data[position : position + copied]
            position += copied
            destination += copied
        else:
            if position >= end:
                raise EOFError("ABMの24bit RLEリテラルがありません。")
            output[destination] = data[position]
            position += 1
            destination += 1
    return bytes(output)


def _decode_abm(data: bytes):
    from PIL import Image

    if len(data) < 0x46 or data[:2] != b"BM":
        raise ValueError("ABM画像のヘッダーが不正です。")
    mode = struct.unpack_from("<h", data, 0x1C)[0]
    width, height = struct.unpack_from("<II", data, 0x12)
    if mode in (1, 2):
        base_offset = struct.unpack_from("<I", data, 0x42)[0]
    elif mode in (32, 24, 8, -8):
        base_offset = struct.unpack_from("<I", data, 0x0A)[0]
    else:
        base_offset = 0
    if not width or not height or width * height > 100_000_000:
        raise ValueError("ABM画像の寸法が不正です。")

    if mode == 1:
        length = width * height * 3
        pixels = data[base_offset : base_offset + length]
        if len(pixels) != length:
            raise EOFError("ABM画像のピクセルデータが途中で終わりました。")
        return Image.frombytes("RGB", (width, height), pixels, "raw", "BGR")

    if mode == 8:
        palette_data = data[0x36 : 0x36 + 256 * 4]
        pixels = data[base_offset : base_offset + width * height]
        if len(palette_data) != 256 * 4 or len(pixels) != width * height:
            raise EOFError("ABM画像のパレットまたはピクセルデータが途中で終わりました。")
        image = Image.frombytes("P", (width, height), pixels)
        palette = []
        for index in range(256):
            blue, green, red = palette_data[index * 4 : index * 4 + 3]
            palette.extend((red, green, blue))
        image.putpalette(palette)
        return image.convert("RGBA")

    if mode == -8:
        palette_data = data[0x36 : 0x36 + 256 * 4]
        if len(palette_data) != 256 * 4:
            raise EOFError("ABM画像のパレットが途中で終わりました。")
        indices = bytearray(width * height)
        alpha = bytearray(width * height)
        position = base_offset
        destination = 0
        while destination < len(indices):
            if position >= len(data):
                raise EOFError(
                    f"ABMの8bit RLEデータが途中で終わりました (出力 {destination}/{len(indices)} ピクセル)。"
                )
            value = data[position]
            position += 1
            if value == 0:
                if position >= len(data):
                    raise EOFError("ABMの8bit RLEスキップ長がありません。")
                count = data[position]
                position += 1
                if count > len(indices) - destination:
                    raise ValueError("ABMの8bit RLEスキップ長が画像の範囲を超えています。")
                destination += count
            elif value == 0xFF:
                if position >= len(data):
                    raise EOFError("ABMの8bit RLEリテラル長がありません。")
                count = data[position]
                position += 1
                if count > len(indices) - destination:
                    raise ValueError("ABMの8bit RLEリテラル長が画像の範囲を超えています。")
                if position + count > len(data):
                    raise EOFError("ABMの8bit RLEリテラルが途中で終わりました。")
                indices[destination : destination + count] = data[position : position + count]
                alpha[destination : destination + count] = b"\xFF" * count
                position += count
                destination += count
            else:
                if position >= len(data):
                    raise EOFError("ABMの8bit RLEアルファ値に対応する色データがありません。")
                indices[destination] = data[position]
                alpha[destination] = value
                position += 1
                destination += 1
        image = Image.frombytes("P", (width, height), bytes(indices))
        palette = []
        for index in range(256):
            blue, green, red = palette_data[index * 4 : index * 4 + 3]
            palette.extend((red, green, blue))
        image.putpalette(palette)
        image.putalpha(bytes(alpha))
        return image.convert("RGBA")

    if mode == 24:
        total = width * height * 3
        output = _unpack_abm24(data, base_offset, total)
        return Image.frombytes("RGB", (width, height), output, "raw", "BGR")

    if mode == 3:
        frame_count = struct.unpack_from("<H", data, 0x3A)[0]
        if not frame_count or frame_count > 0xFF:
            raise ValueError("ABMアニメーションのフレーム数が不正です。")
        table_end = 0x42 + frame_count * 4
        if table_end > len(data):
            raise EOFError("ABMアニメーションのフレーム索引が途中で終わりました。")
        frame_offset = struct.unpack_from("<I", data, 0x42)[0]
        frame_end = (
            struct.unpack_from("<I", data, 0x46)[0]
            if frame_count > 1
            else len(data)
        )
        if frame_offset < table_end or frame_end <= frame_offset or frame_end > len(data):
            raise ValueError("ABMアニメーションの先頭フレーム位置が不正です。")
        output = _unpack_abm24(data, frame_offset, width * height * 3, frame_end)
        return Image.frombytes("RGB", (width, height), output, "raw", "BGR")

    if mode == 32:
        output = _unpack_abm32(data, base_offset, width * height * 4)
        return Image.frombytes("RGBA", (width, height), output, "raw", "BGRA")
    if mode == 2:
        position = 0
        if position + 17 > len(data):
            raise EOFError("ABMフレームデータが途中で終わりました。")
        frame_x, frame_y, frame_width, frame_height = struct.unpack_from("<iiii", data, position)
        position += 17
        if frame_x < 0 or frame_y < 0 or frame_width <= 0 or frame_height <= 0:
            raise ValueError("ABMフレームの寸法が不正です。")
        frame = _unpack_abm32(data, position, frame_width * frame_height * 4)
        canvas = Image.new("RGBA", (width, height), (0, 0, 0, 0))
        frame_image = Image.frombytes("RGBA", (frame_width, frame_height), bytes(frame), "raw", "BGRA")
        canvas.alpha_composite(frame_image, (frame_x, frame_y))
        return canvas

    raise ValueError(f"未対応のABM画像形式です: {mode}")


def _translate_script(
    name: str,
    source: str,
    script_names: set[str] | None = None,
    global_labels: dict[str, str] | None = None,
    resource_names: dict[str, set[str]] | None = None,
    sprite_position_variables: dict[int, tuple[int, int, int, int]] | None = None,
    speaker_ids: dict[str, int] | None = None,
    title: str = "tsukumo",
) -> str:
    stem = Path(name).stem.casefold()
    koi = title == "koi"
    speaker_ids = {} if speaker_ids is None else speaker_ids
    output: list[str] = []
    control_stack: list[dict[str, Any]] = []
    control_number = 0
    choice_number = 0
    pending_buttons: list[tuple[int, str]] = []
    script_names = set() if script_names is None else script_names
    global_labels = {} if global_labels is None else global_labels
    resource_names = {} if resource_names is None else resource_names
    sprite_position_variables = (
        {} if sprite_position_variables is None else sprite_position_variables
    )
    local_labels = {
        line.strip()[1:].strip()
        for line in source.splitlines()
        if line.strip().startswith(":") and not line.strip().startswith("::")
    }

    def label_ref(target: str, command: str) -> str:
        target = target.strip().strip('"')
        if target.lower().endswith(".scr"):
            target = Path(target).stem
        normalized = re.sub(r"[^A-Za-z0-9_]", "_", target).casefold()
        if command != "gsb" and target in local_labels:
            return f"*l_{stem}_{normalized}"
        if command == "gsb" and target.casefold() in {item.casefold() for item in script_names}:
            return f"*s_{normalized}"
        if target.casefold() in global_labels:
            return global_labels[target.casefold()]
        if command == "gsb" and target in local_labels:
            return f"*l_{stem}_{normalized}"
        return f"*s_{normalized}"

    def args_from(text: str) -> list[str]:
        args: list[str] = []
        current = []
        quoted = False
        depth = 0
        for character in text:
            if character == '"':
                quoted = not quoted
            if not quoted and character == "(":
                depth += 1
            elif not quoted and character == ")":
                depth -= 1
            if character == "," and not quoted and depth == 0:
                args.append("".join(current).strip())
                current = []
            else:
                current.append(character)
        if current or text.strip():
            args.append("".join(current).strip())
        return args

    def unquote(value: str) -> str:
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] == '"':
            return value[1:-1]
        return value

    def fullwidth(value: str) -> str:
        converted = []
        for character in value:
            codepoint = ord(character)
            if character == " ":
                converted.append("\u3000")
            elif 0x21 <= codepoint <= 0x7E:
                converted.append(chr(codepoint + 0xFEE0))
            elif 0xFF61 <= codepoint <= 0xFF9F:
                converted.append(unicodedata.normalize("NFKC", character))
            else:
                converted.append(character)
        return "".join(converted)

    def image_path(value: str) -> str | None:
        value = unquote(value).strip().casefold()
        if value in resource_names.get("image", set()):
            return f'image\\{value}.png'
        variants = sorted(
            candidate
            for candidate in resource_names.get("image", set())
            if candidate.startswith(value) and candidate[len(value) :].isdigit()
        )
        return f'image\\{variants[0]}.png' if variants else None

    def control_label(kind: str) -> str:
        nonlocal control_number
        control_number += 1
        return f"*c{stem}_{control_number}{kind}"

    def condition(text: str) -> str:
        text = text.strip().strip("()")
        parts = text.split('"')
        return '"'.join(
            part if index % 2 else re.sub(r"\s+", "", part)
            for index, part in enumerate(parts)
        )

    if stem == "staff":
        output.append("skipoff")

    for line_number, raw_line in enumerate(source.splitlines(), 1):
        line = raw_line.strip()
        if not line or line.startswith("#") or line.startswith("::"):
            continue
        if line.startswith(":"):
            local = re.sub(r"[^A-Za-z0-9_]", "_", line[1:].strip())
            output.append(f"*l_{stem}_{local.casefold()}")
            continue
        if "\t#" in line:
            line = line.split("\t#", 1)[0].rstrip()
        elif " #" in line:
            line = line.split(" #", 1)[0].rstrip()
        if not line:
            continue
        if line.startswith("^"):
            directive = re.match(r"^\^([A-Za-z_]+)\s*(?:\((.*)\))?$", line)
            if not directive:
                continue
            command = directive.group(1).lower()
            argument = (directive.group(2) or "").strip()
            if command in ("gsb", "go", "jp"):
                target = unquote(argument.strip("() "))
                if command == "gsb" and target.lower() == "btnsel" and pending_buttons:
                    choice_number += 1
                    choice_prefix = f"h{stem}_{choice_number}"
                    options = []
                    for button_index, button_text in pending_buttons:
                        options.extend((f'"{button_text}"', f"*{choice_prefix}_{button_index}"))
                    output.append("select " + ",".join(options))
                    for button_index, _ in pending_buttons:
                        output.append(f"*{choice_prefix}_{button_index}")
                        output.append(f"mov %reg,{button_index}")
                        output.append(f"mov %sentaku,{button_index - 1}")
                        output.append(f"goto *{choice_prefix}_d")
                    output.append(f"*{choice_prefix}_d")
                    pending_buttons.clear()
                else:
                    output.append(
                        ("gosub " if command == "gsb" else "goto ")
                        + label_ref(target, command)
                    )
            elif command == "ret":
                output.append("return")
            elif command == "if":
                end_label = control_label("e")
                next_label = control_label("n")
                output.append(f"notif {condition(argument)} goto {next_label}")
                control_stack.append(
                    {
                        "kind": "if",
                        "end": end_label,
                        "next": next_label,
                        "has_else": False,
                        "end_used": False,
                    }
                )
            elif command == "elif":
                if not control_stack or control_stack[-1]["kind"] != "if":
                    raise ValueError(
                        f"{name}:{line_number} の ^elif に対応する ^if がありません。"
                    )
                branch = control_stack[-1]
                if branch["has_else"]:
                    raise ValueError(
                        f"{name}:{line_number} で ^else の後に ^elif があります。"
                    )
                output.append(f"goto {branch['end']}")
                branch["end_used"] = True
                output.append(branch["next"])
                next_label = control_label("n")
                output.append(f"notif {condition(argument)} goto {next_label}")
                branch["next"] = next_label
            elif command == "else":
                if not control_stack or control_stack[-1]["kind"] != "if":
                    raise ValueError(
                        f"{name}:{line_number} の ^else に対応する ^if がありません。"
                    )
                branch = control_stack[-1]
                if branch["has_else"]:
                    raise ValueError(
                        f"{name}:{line_number} に ^else が重複しています。"
                    )
                output.append(f"goto {branch['end']}")
                branch["end_used"] = True
                output.append(branch["next"])
                branch["next"] = None
                branch["has_else"] = True
            elif command == "endi":
                if control_stack and control_stack[-1]["kind"] == "switch":
                    # Some source scripts use ^endi to terminate a switch case.
                    output.append(f"goto {control_stack[-1]['end']}")
                    control_stack[-1]["end_used"] = True
                elif not control_stack or control_stack[-1]["kind"] != "if":
                    raise ValueError(
                        f"{name}:{line_number} の ^endi に対応する ^if がありません。"
                    )
                else:
                    branch = control_stack.pop()
                    if branch["next"] is not None:
                        output.append(branch["next"])
                    if branch["end_used"]:
                        output.append(branch["end"])
            elif command == "sw":
                control_stack.append(
                    {
                        "kind": "switch",
                        "expression": argument.strip("()"),
                        "end": control_label("e"),
                        "next": control_label("n"),
                        "cases": 0,
                        "has_default": False,
                        "end_used": False,
                    }
                )
            elif command == "case":
                if not control_stack or control_stack[-1]["kind"] != "switch":
                    raise ValueError(
                        f"{name}:{line_number} の ^case に対応する ^sw がありません。"
                    )
                switch = control_stack[-1]
                if switch["has_default"]:
                    raise ValueError(
                        f"{name}:{line_number} で ^df の後に ^case があります。"
                    )
                if switch["cases"]:
                    output.append(f"goto {switch['end']}")
                    switch["end_used"] = True
                    output.append(switch["next"])
                next_label = control_label("n")
                output.append(
                    f"notif {condition(switch['expression'] + '==' + argument)} "
                    f"goto {next_label}"
                )
                switch["next"] = next_label
                switch["cases"] += 1
            elif command == "df":
                if not control_stack or control_stack[-1]["kind"] != "switch":
                    raise ValueError(
                        f"{name}:{line_number} の ^df に対応する ^sw がありません。"
                    )
                switch = control_stack[-1]
                if switch["has_default"]:
                    raise ValueError(f"{name}:{line_number} に ^df が重複しています。")
                output.append(f"goto {switch['end']}")
                switch["end_used"] = True
                output.append(switch["next"])
                switch["has_default"] = True
            elif command == "ends":
                if not control_stack or control_stack[-1]["kind"] != "switch":
                    raise ValueError(
                        f"{name}:{line_number} の ^ends に対応する ^sw がありません。"
                    )
                switch = control_stack.pop()
                if not switch["has_default"]:
                    output.append(switch["next"])
                if switch["end_used"]:
                    output.append(switch["end"])
            continue
        if line.lower().startswith("var "):
            continue
        if line.lower() in (
            "wout",
            "wndoff",
            "bgoff",
            "pause",
            "btnenable",
            "loadenable",
            "saveenable",
            "loaddisable",
            "savedisable",
            "clrbacklog",
            "backtitle",
            "wbl",
            "bgmoff",
            "exit",
        ):
            if line.lower() == "wout":
                output.append("print 1")
            elif line.lower() == "wndoff":
                output.append("erasetextwindow 1:csp 0:csp 1")
            elif line.lower() == "bgoff":
                output.append("csp 999:print 10")
            elif line.lower() == "pause":
                output.append("click")
            elif line.lower() == "backtitle":
                output.append("goto *title")
            elif line.lower() == "bgmoff":
                if stem == "staff":
                    output.append("click")
                output.append("bgmstop")
            elif line.lower() == "exit":
                output.append("end")
            continue
        call = re.match(r"^([A-Za-z_][A-Za-z0-9_]*)\s*\((.*)\)\s*$", line)
        if call:
            command = call.group(1).lower()
            args = args_from(call.group(2))
            first = args[0] if args else ""
            second = args[1] if len(args) > 1 else ""
            if koi and command == "efex" and len(args) >= 2:
                # 恋する少女: efex(ch,12,x,y,画像,..)=立ち絵登場, (ch,13,..)=退場,
                # (ch,11,x,y)=移動, (-1,n,ms)=描画(即時反映のため画面更新のみ)
                mode = args[1].strip()
                if mode == "12" and len(args) >= 5:
                    command, args = "chon", [args[0], args[4], args[2], args[3]]
                    first, second = args[0], args[1]
                elif mode == "13":
                    command, args = "choff", [args[0]]
                    first = args[0]
                elif mode == "11" and len(args) >= 4:
                    move_variables = sprite_position_variables[int(first)]
                    output.append(f"mov %{move_variables[0]},{args[2]}")
                    output.append(f"mov %{move_variables[1]},{args[3]}")
                    output.append(f"mov %{move_variables[2]},0")
                    output.append(
                        f"if %{move_variables[3]}==1 gosub *p{int(first)}"
                    )
                    continue
                else:
                    if first == "-1":
                        output.append("print 10")
                    continue
            if command in ("bgon", "cgon"):
                asset = unquote(first).lower()
                resolved = image_path(first)
                if asset in ("white", "black"):
                    sprite = "$92" if asset == "white" else "$91"
                    output.append(f"lsp 999,{sprite},0,0")
                elif resolved:
                    output.append(f'lsp 999,"{resolved}",0,0')
                else:
                    output.append(f"; missing image resource: {unquote(first)}")
            elif command == "chon" and len(args) >= 2:
                channel = int(first)
                sprite_id = 100 - channel
                position_variables = sprite_position_variables.get(channel)
                asset = unquote(second).lower()
                if asset in ("white", "black"):
                    sprite = "$92" if asset == "white" else "$91"
                else:
                    resolved = image_path(second)
                    sprite = f'"{resolved}"' if resolved else ""
                if sprite:
                    x = args[2].strip().upper() if len(args) > 2 else "NON"
                    y = (
                        args[3].strip().upper()
                        if len(args) > 3
                        else "CENTER"
                        if x == "CENTER"
                        else "NON"
                        if x == "NON"
                        else "0"
                    )
                    if position_variables is None:
                        raise ValueError(f"立ち絵チャンネル {channel} の位置変数がありません。")
                    (
                        x_variable,
                        y_variable,
                        y_center_variable,
                        active_variable,
                    ) = position_variables
                    if x == "CENTER":
                        output.append(f"mov %{x_variable},512")
                    elif x.lstrip("-").isdigit():
                        output.append(f"mov %{x_variable},{x}")
                    if y == "CENTER":
                        output.append(f"mov %{y_center_variable},1")
                    elif y != "NON":
                        output.append(f"mov %{y_variable},{y}")
                        output.append(f"mov %{y_center_variable},0")
                    output.append(f"lsp {sprite_id},{sprite},0,0")
                    collides = x == "NON" and channel in (1, 2, 3) and not koi
                    output.append(f"gosub *{'q' if collides else 'r'}{channel}")
                else:
                    output.append(f"; missing image resource: {unquote(second)}")
            elif command == "choff" and args:
                channel = int(first)
                if channel in (-1, 18):
                    output.append("gosub *ca")
                else:
                    output.append(f"gosub *o{channel}")
            elif command == "bgmon" and args:
                asset = unquote(first)
                if asset.casefold() in resource_names.get("bgm", set()):
                    output.append(f'bgm "bgm\\{asset}.ogg"')
                else:
                    output.append(f"; missing BGM resource: {asset}")
            elif command in ("bgmoff", "seoff", "envoff"):
                output.append("bgmstop" if command == "bgmoff" else "dwavestop -1")
            elif command == "seon" and args:
                asset = unquote(first)
                if asset.casefold() in resource_names.get("se", set()):
                    output.append(f'dwave 1,"se\\{asset}.ogg"')
                else:
                    output.append(f"; missing SE resource: {asset}")
            elif command == "cvon" and args:
                asset = unquote(first)
                if asset.casefold() in resource_names.get("voice", set()):
                    output.append(f'dwave 0,"voice\\{asset}.ogg"')
                else:
                    output.append(f"; missing voice resource: {asset}")
            elif command == "envon" and args:
                asset = unquote(first)
                if asset.casefold() in resource_names.get("se", set()):
                    output.append(f'dwave 2,"se\\{asset}.ogg"')
                else:
                    output.append(f"; missing SE resource: {asset}")
            elif command == "ud":
                output.append("print 1" if not args or args[0] == "0" else "print 10")
            elif command == "wait" and args:
                output.append(f"wait {args[0]}")
            elif command == "rand" and args:
                output.append(f"rnd %reg,{int(args[0]) + 1}")
            elif command == "wout":
                output.append("print 1")
            elif command == "global" and len(args) > 1:
                output.append(f"mov {args[0]},{args[1]}")
            elif command == "btnset" and len(args) > 1:
                if len(args) > 4:
                    try:
                        index = int(args[0])
                    except ValueError:
                        index = 0
